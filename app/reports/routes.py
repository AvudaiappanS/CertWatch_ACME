"""PDF report generation with ReportLab and CSV export."""
import csv
import io
from datetime import datetime

from flask import Blueprint, Response
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (Paragraph, SimpleDocTemplate, Spacer, Table,
                                TableStyle)

from ..auth.routes import login_required, role_required
from ..models import Alert, AuditLog, Certificate, CTFinding, Renewal, ScanResult

reports_bp = Blueprint("reports", __name__, url_prefix="/reports")


@reports_bp.route("/")
@role_required("Administrator")
def index():
    """Reports & History page: scan history, CSV export and the audit log."""
    scans = (ScanResult.query.order_by(ScanResult.scan_time.desc())
             .limit(50).all())
    entries = AuditLog.query.order_by(AuditLog.ts.desc()).limit(50).all()
    return __import__("flask").render_template("reports.html", scans=scans,
                                               entries=entries)


@reports_bp.route("/scans.csv")
@login_required
def scans_csv():
    """CSV export of the scan history (the Export CSV button)."""
    out = io.StringIO()
    writer = csv.writer(out)
    writer.writerow(["time_utc", "domain", "days_remaining", "risk_score",
                     "risk_reasons", "result", "error"])
    for s in ScanResult.query.order_by(ScanResult.scan_time.desc()).limit(1000).all():
        writer.writerow([s.scan_time.strftime("%Y-%m-%d %H:%M"),
                         s.certificate.domain if s.certificate else "?",
                         s.days_remaining if s.days_remaining is not None else "",
                         s.risk_score if s.risk_score is not None else "",
                         s.risk_reasons or "", s.status, s.error or ""])
    return Response(out.getvalue(), mimetype="text/csv", headers={
        "Content-Disposition": "attachment; filename=scan_history.csv"})


def _table(data, widths=None):
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1e3a5f")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f2f6fa")]),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    return t


def _pdf_response(title, build):
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, title=title,
                            leftMargin=15 * mm, rightMargin=15 * mm)
    styles = getSampleStyleSheet()
    story = [Paragraph(title, styles["Title"]),
             Paragraph(f"Generated by CertWatch Lab on "
                       f"{datetime.utcnow():%Y-%m-%d %H:%M} UTC", styles["Normal"]),
             Spacer(1, 8 * mm)]
    build(story, styles)
    doc.build(story)
    return Response(buf.getvalue(), mimetype="application/pdf", headers={
        "Content-Disposition": f"attachment; filename={title.lower().replace(' ', '_')}.pdf"})


@reports_bp.route("/certificates.pdf")
@login_required
def certificates_pdf():
    certs = Certificate.query.order_by(Certificate.domain).all()

    def build(story, styles):
        data = [["Domain", "Issuer (CN)", "Expiry (UTC)", "Days", "Status", "Verified"]]
        for c in certs:
            issuer = (c.issuer or "").split(",")[0][:40]
            data.append([c.domain, issuer,
                         c.expiry_date.strftime("%Y-%m-%d") if c.expiry_date else "-",
                         str(c.days_remaining if c.days_remaining is not None else "-"),
                         c.status or "-", "yes" if c.verified else "NO"])
        story.append(_table(data))
    return _pdf_response("Certificate Status Report", build)


@reports_bp.route("/ct.pdf")
@login_required
def ct_pdf():
    findings = CTFinding.query.order_by(CTFinding.similarity_score.desc()).all()

    def build(story, styles):
        data = [["Protected", "Detected look-alike", "Similarity", "Risk", "First seen"]]
        for f in findings:
            data.append([f.protected_domain, f.detected_domain,
                         f"{f.similarity_score}%", f.risk_level,
                         f.first_seen.strftime("%Y-%m-%d")])
        story.append(_table(data, widths=[35 * mm, 60 * mm, 20 * mm, 20 * mm, 25 * mm]))
    return _pdf_response("CT Look-alike Findings", build)


@reports_bp.route("/renewals.pdf")
@login_required
def renewals_pdf():
    rows = Renewal.query.order_by(Renewal.created_at.desc()).all()

    def build(story, styles):
        data = [["Date (UTC)", "Domain", "Mode", "Old expiry", "New expiry", "Status"]]
        for r in rows:
            domain = r.certificate.domain if r.certificate else "?"
            data.append([r.created_at.strftime("%Y-%m-%d %H:%M"), domain,
                         r.acme_mode or "-",
                         r.old_expiry.strftime("%Y-%m-%d") if r.old_expiry else "-",
                         r.new_expiry.strftime("%Y-%m-%d") if r.new_expiry else "-",
                         r.status])
        story.append(_table(data))
    return _pdf_response("Renewal History", build)


